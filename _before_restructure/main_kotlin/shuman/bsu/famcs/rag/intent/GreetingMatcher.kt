package shuman.bsu.famcs.rag.intent

/**
 * Узнаёт сообщения, которые целиком состоят из приветствия, прощания или благодарности.
 *
 * Правила перенесены из Python-версии (`_SMALLTALK_STRICT`). «Строго» значит: сообщение — только такая фраза и знаки
 * препинания. «Привет, а какой проходной балл?» приветствием не считается и идёт дальше по обычному пути.
 * Исправлено при переносе: «пока\w*» в Python принимало и «покажи», теперь «пока» только целым словом.
 */
class GreetingMatcher {
    fun isGreeting(text: String): Boolean = PATTERN.matches(text.trim())

    private companion object {
        // (?U) включает юникодное значение \w и \s для кириллицы.
        val PATTERN = Regex(
            "(?U)\\s*(" +
                "привет\\w*|здравствуй\\w*|здрасьте|" +
                "добрый\\s+(день|вечер|утро|полдень)|" +
                "доброго\\s+(дня|вечера|утра)|" +
                "((большое|огромное)\\s+)?спасибо\\w*(\\s+(большое|огромное))?|благодарю|пасиб|" +
                "пока(-пока)?|до\\s+свидания|прощай\\w*|" +
                "как\\s+дела|что\\s+нового|как\\s+ты|как\\s+жизнь|" +
                "hi|hello|hey|thanks|thank\\s+you" +
                ")\\s*[!?.…,]*\\s*",
            RegexOption.IGNORE_CASE,
        )
    }
}
