package shuman.bsu.famcs.rag.quality.judge.model

/**
 * Класс ответа по корректности (против эталона). Подробнее двоичного вердикта: разбор 2026-10-21 показал, что судья признавал
 * неверными ответы, которые содержат эталон и больше (38 из 38 спорных человек признал верными).
 *
 * @property verdict двоичный вердикт для сверки с человеком и прежних отчётов.
 */
enum class CorrectnessGrade(
    val verdict: Verdict,
) {
    /** Ответ передаёт главные факты эталона. */
    CORRECT(Verdict.PASS),

    /** Факты эталона есть, плюс дополнительные сведения. Лишнее эталоном не проверить: его проверяет критерий верности. */
    CORRECT_PLUS(Verdict.PASS),

    /** Есть только часть фактов эталона, противоречий нет. */
    PARTIAL(Verdict.FAIL),

    /** Ответ противоречит эталону или называет другой факт. */
    WRONG(Verdict.FAIL),

    /** Ответ сообщает, что информации нет. */
    REFUSAL(Verdict.FAIL),

    /** Сравнить нельзя. */
    UNKNOWN(Verdict.UNKNOWN),
}
