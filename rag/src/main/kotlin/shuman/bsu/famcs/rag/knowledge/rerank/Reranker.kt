package shuman.bsu.famcs.rag.knowledge.rerank

/**
 * Оценивает, насколько каждый найденный фрагмент отвечает на вопрос.
 *
 * Поиск по векторам быстрый, но грубый. Реранкер читает пару «вопрос и фрагмент» целиком и оценивает точнее,
 * поэтому из десятка кандидатов поиска остаются три лучших. Реализация подменяется (ONNX на процессоре,
 * внешний сервис), остальной код видит только этот интерфейс.
 */
interface Reranker {
    /** Оценки релевантности от 0 до 1 для каждого фрагмента, в том же порядке, что и [passages]. */
    suspend fun score(
        query: String,
        passages: List<String>,
    ): List<Double>
}
