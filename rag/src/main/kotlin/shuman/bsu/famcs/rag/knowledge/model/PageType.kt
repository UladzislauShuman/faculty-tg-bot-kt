package shuman.bsu.famcs.rag.knowledge.model

/**
 * Тип страницы сайта. Определяется при индексации и хранится у каждого фрагмента: по нему поиск отличает основную страницу
 * от перечня новостей или хроники года, и это влияет на порядок выдачи ([shuman.bsu.famcs.rag.knowledge.retrieval.RankingPolicy]).
 */
enum class PageType {
    /** Основной раздел или страница: правила, структура, приём, деканат. Самая надёжная для справочных вопросов. */
    SECTION,

    /** Новость или статья (`page-node-type-article`). Короткая, описывает событие в своё время. */
    NEWS,

    /** Хроника по году (`history-ГГГГ`): много событий года на одной странице. */
    HISTORY,

    /** Перечень со ссылками без собственного содержания: главная страница, списки по теме (`path-taxonomy`). */
    LIST,

    /** Кафедра (`kafedra-…`). */
    DEPARTMENT,

    /** Каталог учебных дисциплин. */
    CATALOG,

    /** Мероприятие или архив с годом в адресе (конференции, олимпиады по годам). */
    EVENT,
}
