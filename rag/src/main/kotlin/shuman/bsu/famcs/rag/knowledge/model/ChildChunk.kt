package shuman.bsu.famcs.rag.knowledge.model

/** Мелкий фрагмент (около 300 символов): по нему идёт поиск. Принадлежит разделу-родителю [ParentChunk]. */
data class ChildChunk(
    /** Стабильный идентификатор: хеш адреса и текста. Тот же фрагмент даёт тот же идентификатор. */
    val id: String,
    val parentId: String,
    val text: String,
    /**
     * Заголовки раздела, из которого взят фрагмент. Нужны, когда родитель объединяет несколько разделов (маленькая страница целиком):
     * контекст фрагмента строится по его собственному разделу. Пусто — берутся заголовки родителя.
     */
    val headings: Map<String, String> = emptyMap(),
)
