package shuman.bsu.famcs.rag.quality.judge.model

/** Вердикт судьи по одному критерию. */
enum class Verdict {
    /** Критерий выполнен. */
    PASS,

    /** Критерий нарушен. */
    FAIL,

    /** Судья не смог решить по данным. Считается отдельно и в таблицу согласия с человеком не входит. */
    UNKNOWN,
}
