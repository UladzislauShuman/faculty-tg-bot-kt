package shuman.bsu.famcs.rag.api.model

/**
 * Трасса ответа: что система сделала с вопросом по шагам.
 * Нужна проверкам качества и разбору сбоев: по ней видно, на каком шаге ошибка (переформулировка, ветка, поиск, генерация).
 * Адаптер Telegram её не показывает; HTTP-вход отдаёт её по запросу.
 */
data class AnswerTrace(
    /** Выбранная ветка (`RAG`, `SMALLTALK`, `GENERAL`, `SCHEDULE`). */
    val route: String,
    /** Самостоятельный запрос после переформулирования; равен вопросу, если переформулировки не было. */
    val query: String,
    /** Разделы, которые увидела модель, в порядке реранкера. Пусто, если поиск не выполнялся. */
    val passages: List<TracePassage>,
    /** Кандидаты поиска в порядке реранкера с оценками и отметкой «выбран»: видно, куда реранкер поставил нужный раздел. */
    val candidates: List<TraceCandidate>,
    /** Время гибридного поиска, реранкера и генерации ответа, мс. */
    val searchMs: Long,
    val rerankMs: Long,
    val generationMs: Long,
    /** Провайдер и модель, сформировавшие ответ. `null`, если модель не вызывалась. */
    val provider: String?,
    val model: String?,
    /** Токены всего вопроса: переформулировка, классификатор и ответ вместе. */
    val tokensIn: Int,
    val tokensOut: Int,
)
