package shuman.bsu.famcs.rag.knowledge.model

/**
 * Крупный раздел документа (около 1200 символов): уходит в промпт как контекст.
 *
 * Схема «родитель и ребёнок»: поиск идёт по мелким фрагментам ([ChildChunk]), чтобы точно попасть в смысл вопроса,
 * а в промпт уходит раздел целиком, чтобы модели хватило контекста.
 */
data class ParentChunk(
    val id: String,
    val text: String,
    /** Заголовки, под которыми лежит раздел (`H1`, `H2`, `H3`). */
    val headings: Map<String, String>,
)
